#!/usr/bin/env python3
"""html_docs_to_md.py -- Convert an HTML documentation site into Markdown
.md files: one .md per documentation section, containing the full text of all
its child pages, with site chrome / boilerplate stripped. Plain-text .txt
output is available as a fallback (--format txt), and is used automatically
if the Markdown libraries are unavailable.

Two conversion paths:
  Markdown (default) -- html2text + beautifulsoup4, loaded from the skill's
      private venv (scripts/.venv, created by scripts/ensure_venv.sh). The
      script re-executes itself with the venv interpreter when needed.
  txt (fallback)     -- stdlib-only extraction, no dependencies, identical
      to the original html-docs-to-txt behavior.

Modes:
  auto     detect the generator automatically (default)
  doxygen  parse navtreedata.js NAVTREE for the exact page/section tree
  crawl    BFS-crawl same-host .html links (MkDocs, Docusaurus, plain HTML)

Usage:
  python3 html_docs_to_md.py URL [options]

Options:
  --out DIR       output directory (default: ./docs_md/<site-name>)
  --format F      md | txt                        (default: md)
  --txt           shorthand for --format txt
  --mode M        auto | doxygen | crawl          (default: auto)
  --flat          write ONE combined file instead of one per section
  --per-page      write one file per page instead of per section
  --max-pages N   crawl limit in crawl mode       (default: 200)
  --delay S       politeness delay between fetches, seconds (default: 0.2)
  --strip RE      extra boilerplate regex, applied per line (repeatable)
  --index-min N   "index page" expansion threshold (default: 1500 chars)
  --ua STR        User-Agent header                (default: Mozilla/5.0 ...)
  --quiet         suppress progress output
"""
import argparse
import os
import re
import sys
import time
import urllib.parse
import urllib.request
from html.parser import HTMLParser
from pathlib import Path

CONTENT_IDS = {"doc-content", "content", "main-content", "documentation",
               "docs-content", "wiki-content", "markdown-section"}
CONTENT_CLASSES = {"markdown-section", "theme-doc-markdown", "md-content",
                   "document", "contents", "doc"}
BOILERPLATE = [
    r"^(Loading|Searching|No Matches|Search)[. …]*$",
    r"^Generated by [\d.]+$",
    r"^Click to (search|show|hide).*$",
]
EXTERNAL_URL_PREFIXES = ("http://", "https://", "//", "#", "mailto:",
                         "data:", "tel:")

VENV_PY = Path(__file__).resolve().parent / ".venv" / "bin" / "python3"

# ---------------------------------------------------------------- markdown deps

try:
    import bs4            # noqa: F401
    import html2text      # noqa: F401
    HAVE_MD_LIBS = True
except ImportError:
    HAVE_MD_LIBS = False


def try_venv_reexec():
    """Re-run this script with the venv interpreter so the Markdown path
    becomes available. Returns only if re-exec is not possible. The guard
    compares sys.prefix (not resolved executable paths) because venv
    pythons are symlinks to the system interpreter, which would make a
    path comparison false-negative and skip the hop."""
    venv_dir = str(VENV_PY.parent.parent)
    if VENV_PY.exists() and sys.prefix != venv_dir:
        try:
            os.execv(str(VENV_PY), [str(VENV_PY)] + sys.argv)
        except OSError:
            pass

# ---------------------------------------------------------------- HTTP layer

def make_fetcher(ua, delay):
    cache = {}

    def fetch(url):
        if url not in cache:
            for attempt in range(3):
                try:
                    req = urllib.request.Request(url, headers={"User-Agent": ua})
                    with urllib.request.urlopen(req, timeout=30) as r:
                        cache[url] = r.read().decode("utf-8", "replace")
                    break
                except Exception as e:
                    if attempt == 2:
                        sys.stderr.write(f"WARN: fetch failed {url}: {e}\n")
                        cache[url] = ""
                    else:
                        time.sleep(delay + attempt)
            time.sleep(delay)
        return cache[url]

    return fetch


def sanitize(name):
    name = re.sub(r"[^\w\s-]", "", name).strip()
    return re.sub(r"[\s-]+", "_", name)[:60] or "page"


def normalize_unicode(raw):
    """Non-breaking spaces are normalized FIRST -- they otherwise silently
    defeat exact-match boilerplate stripping. Zero-width joiners are
    invisible but corrupt plain-text search and diffing."""
    return raw.replace("\xa0", " ").replace("‌", "").replace("‍", "")


# ---------------------------------------------------------------- navigation

def navtree_sections(fetch, base):
    """Doxygen: parse var NAVTREE in navtreedata.js.

    Returns [(section_title, [page_url, ...]), ...]. Top-level entries are
    sections; unique .html descendants are child pages. Entries whose url is
    an anchor (page.html#frag) are skipped: their text already lives inside
    the parent page's HTML.
    """
    js = fetch(urllib.parse.urljoin(base, "navtreedata.js"))
    if not js or "var NAVTREE" not in js:
        # older Doxygen versions ship the same NAVTREE in navtree.js
        js = fetch(urllib.parse.urljoin(base, "navtree.js"))
    if not js or "var NAVTREE" not in js:
        return []
    start = js.index("var NAVTREE")
    end = re.search(r"\];", js[start:])
    body = js[start:start + (end.end() if end else len(js) - start)]
    toks = re.findall(r'"(?:[^"\\]|\\.)*"|\[|\]', body)

    def parse(i):
        out = []
        while i < len(toks):
            t = toks[i]
            if t == "[":
                sub, i = parse(i + 1)
                out.append(sub)
            elif t == "]":
                return out, i + 1
            else:
                out.append(t.strip('"'))
                i += 1
        return out, i

    tree, _ = parse(0)
    sections = []

    def urls(node):
        got = []
        for ch in node:
            if isinstance(ch, list):
                # recurse into every list child; a bare container list has a
                # non-string second element and must not be skipped
                if len(ch) >= 2 and isinstance(ch[1], str) and ch[1].endswith(".html"):
                    got.append(ch[1])
                got.extend(urls(ch))
        return got

    # unwrap wrapper lists: NAVTREE = [ [ "Site", "index.html", [sec, ...] ] ]
    # descend through single-entry wrappers to reach the root entry.
    node = tree
    while isinstance(node, list) and len(node) == 1 and isinstance(node[0], list):
        node = node[0]
    # node is now the root entry [title, index.html, [sections...]]; keep the
    # root page (site home / main page) as its own first section
    root_title = root_url = None
    if isinstance(node, list) and len(node) >= 2 and isinstance(node[0], str) \
            and isinstance(node[1], str) and node[1].endswith(".html"):
        root_title, root_url = node[0], node[1]
    # its list element holds the top-level sections
    tops = [x for x in node if isinstance(x, list)] if isinstance(node, list) else []
    if len(tops) == 1 and tops[0] and all(isinstance(x, list) for x in tops[0]):
        tops = tops[0]  # unwrap [site, url, [section, ...]] -> [section, ...]
    for top in tops:
        if len(top) >= 2 and isinstance(top[0], str) and isinstance(top[1], str):
            pages = []
            if top[1].endswith(".html"):
                pages.append(top[1])
            pages.extend(urls(top))
            seen, uniq = set(), []
            for p in pages:
                if p not in seen:
                    seen.add(p)
                    uniq.append(p)
            if uniq:
                sections.append((top[0], uniq))
    if root_url:
        sections.insert(0, (root_title, [root_url]))
    return sections


def crawl_pages(fetch, base, max_pages):
    """Generic: BFS same-host .html links. Returns ordered list of URLs."""
    start = urllib.parse.urlparse(base)
    seen, order, queue = set(), [], [base.rstrip("/") + "/"]
    while queue and len(order) < max_pages:
        url = queue.pop(0)
        if url in seen:
            continue
        seen.add(url)
        html = fetch(url)
        if not html:
            continue
        order.append(url)
        for m in re.finditer(r'href="([^"#]+\.html?)"', html):
            u = urllib.parse.urljoin(url, m.group(1))
            p = urllib.parse.urlparse(u)
            if p.netloc == start.netloc and u not in seen:
                queue.append(u)
    return order


# ---------------------------------------------------------------- txt path (stdlib fallback)

class Extractor(HTMLParser):
    """Collect plain text from the main content container; fall back to
    <body> minus nav/header/footer/aside/script/style."""
    SKIP = {"script", "style", "nav", "header", "footer", "aside",
            "noscript", "svg", "form", "button"}
    BLOCK = {"p", "div", "h1", "h2", "h3", "h4", "h5", "h6", "li", "tr",
             "dt", "dd", "pre", "table", "blockquote", "section", "br"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.skip = 0
        self.body_buf = []
        self.stack = []      # [tag, buf] for open content containers
        self.candidates = []

    def _is_content(self, tag, attrs):
        d = dict(attrs)
        if tag in ("main", "article") or d.get("id") in CONTENT_IDS:
            return True
        if d.get("role") == "main":
            return True
        return bool(set((d.get("class") or "").split()) & CONTENT_CLASSES)

    def handle_starttag(self, tag, attrs):
        if tag in self.SKIP:
            self.skip += 1
        if tag in self.BLOCK:
            self._emit("\n")
        if tag in ("td", "th"):
            self._emit(" | ")
        if not self.stack and self._is_content(tag, attrs):
            self.stack.append([tag, []])
        elif self.stack and tag == self.stack[-1][0]:
            self.stack.append([tag, []])

    def handle_endtag(self, tag):
        if tag in self.SKIP and self.skip:
            self.skip -= 1
        if self.stack and tag == self.stack[-1][0]:
            _, buf = self.stack.pop()
            self.candidates.append("".join(buf))
        if tag in self.BLOCK:
            self._emit("\n")

    def handle_data(self, data):
        self._emit(data)

    def _emit(self, text):
        if self.skip:
            return
        for c in self.stack:
            c[1].append(text)
        if not self.stack:
            self.body_buf.append(text)


def to_text(html, extra_strip=()):
    """HTML -> cleaned plain text (stdlib only; the txt fallback path)."""
    p = Extractor()
    try:
        p.feed(html)
    except Exception:
        pass
    raw = max(p.candidates, key=len) if p.candidates else "".join(p.body_buf)
    raw = normalize_unicode(raw)
    pats = [re.compile(x) for x in BOILERPLATE] + \
           [re.compile(x) for x in extra_strip]
    lines = [ln for ln in raw.split("\n")
             if not any(pat.match(ln.strip()) for pat in pats)]
    txt = "\n".join(lines)
    txt = re.sub(r"[ \t]+", " ", txt)
    txt = re.sub(r"\n\s*\n+", "\n\n", txt)
    return txt.strip() + "\n"


# ---------------------------------------------------------------- markdown path (venv)

def extract_content_html(html):
    """Return the inner HTML of the main content container, with chrome
    (nav/header/footer/aside/script/style/...) removed. Falls back to
    <body>, then to the whole document."""
    soup = bs4.BeautifulSoup(html, "html.parser")
    el = None
    for sel in ("#doc-content", "main", "article", '[role="main"]'):
        try:
            el = soup.select_one(sel)
        except Exception:
            el = None
        if el:
            break
    if not el:
        for cls in sorted(CONTENT_CLASSES):
            el = soup.find(class_=cls)
            if el:
                break
    if not el:
        el = soup.body
    if el is None:
        el = soup
    for tag in el.find_all(["script", "style", "nav", "header", "footer",
                            "aside", "noscript", "svg", "form", "button"]):
        tag.decompose()
    return el.decode_contents()


def absolutize_urls(md, page_url):
    """Rewrite relative link/image URLs to absolute ones, so the .md stays
    usable when read offline. Images and links share the [..](..) shape."""
    def fix(m):
        label, url = m.group(1), m.group(2)
        if url.startswith(EXTERNAL_URL_PREFIXES):
            return m.group(0)
        return f"[{label}]({urllib.parse.urljoin(page_url, url)})"
    return re.sub(r"\[([^\]]*)\]\(([^)\s]+)\)", fix, md)


def dedent_fences(md):
    """html2text indents <pre> content by 4 spaces; inside a ``` fence that
    indentation is literal and renders as extra indent, so strip the common
    leading whitespace of each fenced block."""
    lines = md.split("\n")
    out, i = [], 0
    while i < len(lines):
        if lines[i].startswith("```"):
            out.append(lines[i])
            i += 1
            block = []
            while i < len(lines) and not lines[i].startswith("```"):
                block.append(lines[i])
                i += 1
            if block:
                ind = min((len(ln) - len(ln.lstrip())
                           for ln in block if ln.strip()), default=0)
                out.extend(ln[ind:] if ln.strip() else "" for ln in block)
            if i < len(lines):
                out.append(lines[i])
                i += 1
        else:
            out.append(lines[i])
            i += 1
    return "\n".join(out)


def to_markdown(html, page_url, extra_strip=()):
    """HTML -> cleaned Markdown via html2text (venv). Content-container
    extraction happens on the HTML side so nav/search chrome never reaches
    the converter; boilerplate is then stripped per line."""
    h = html2text.HTML2Text()
    h.body_width = 0          # no hard wrapping: keeps headings/URLs intact
    h.mark_code = True        # bracket <pre> blocks, so they can be fenced
    h.unicode_snob = True     # keep unicode instead of HTML entities
    h.ignore_images = False
    h.ignore_tables = False
    h.pad_table = True

    content = extract_content_html(html)
    md = h.handle(content)
    md = normalize_unicode(md).replace("&nbsp;", " ")
    # mark_code wraps <pre> in [code]...[/code]; turn those markers into
    # ``` fences so the output is real fenced Markdown
    md = re.sub(r"\[/?code\][ \t]*", "```", md)
    pats = [re.compile(x) for x in BOILERPLATE] + \
           [re.compile(x) for x in extra_strip]
    lines = [ln.rstrip() for ln in md.split("\n")
             if not any(pat.match(ln.strip()) for pat in pats)]
    md = "\n".join(lines)
    md = dedent_fences(md)
    md = absolutize_urls(md, page_url)
    md = re.sub(r"\n{3,}", "\n\n", md)
    return md.strip() + "\n"


# ---------------------------------------------------------------- headers

def txt_header(title, url):
    return "=" * 78 + f"\n{title}  ({url})\n" + "=" * 78 + "\n"


def md_page_block(md, url):
    """Page separator for combined .md files. The page's own first heading
    (if any) serves as its title, so a duplicate title is only emitted when
    the content has no top heading."""
    block = f"\n---\n\n> Source: <{url}>\n\n"
    if not md.lstrip().startswith("#"):
        stem = Path(urllib.parse.urlparse(url).path).stem or "page"
        block += f"## {stem}\n\n"
    return block + md


# ---------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description="HTML docs site -> .md files "
                                             "(plain-text .txt fallback)")
    ap.add_argument("url")
    ap.add_argument("--out")
    ap.add_argument("--format", choices=["md", "txt"], default="md")
    ap.add_argument("--txt", action="store_true",
                    help="shorthand for --format txt")
    ap.add_argument("--mode", choices=["auto", "doxygen", "crawl"], default="auto")
    ap.add_argument("--flat", action="store_true")
    ap.add_argument("--per-page", action="store_true")
    ap.add_argument("--max-pages", type=int, default=200)
    ap.add_argument("--delay", type=float, default=0.2)
    ap.add_argument("--strip", action="append", default=[])
    ap.add_argument("--index-min", type=int, default=1500,
                    help="pages with text shorter than this are treated as "
                         "index pages and expanded with their child pages")
    ap.add_argument("--ua", default="Mozilla/5.0 (X11; Linux x86_64) docs-to-md/2.0")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args()

    fmt = "txt" if a.txt else a.format
    if fmt == "md" and not HAVE_MD_LIBS:
        # try to hop into the venv; if that is impossible, degrade to txt
        try_venv_reexec()
        sys.stderr.write(
            "WARN: html2text/beautifulsoup4 unavailable -- falling back to "
            "plain-text .txt output.\n"
            "      Enable Markdown: bash scripts/ensure_venv.sh\n")
        fmt = "txt"
    ext = ".md" if fmt == "md" else ".txt"

    # a URL pointing at a page (e.g. .../html/index.html) -> use its directory
    base = a.url.rstrip("/")
    if base.endswith(".html") or base.endswith(".htm"):
        base = base.rsplit("/", 1)[0]
    base += "/"
    fetch = make_fetcher(a.ua, a.delay)
    say = (lambda *x: None) if a.quiet else print

    sections = []
    if a.mode in ("auto", "doxygen"):
        sections = navtree_sections(fetch, base)
    if sections and a.mode != "crawl":
        say(f"[mode] doxygen navtree: {len(sections)} sections")
    else:
        pages = crawl_pages(fetch, base, a.max_pages)
        say(f"[mode] crawl: {len(pages)} pages")
        groups = {}
        for u in pages:
            parts = [x for x in urllib.parse.urlparse(u).path.split("/") if x]
            key = parts[0] if len(parts) > 1 else "root"
            groups.setdefault(key, []).append(u)
        order = ["root"] + [k for k in groups if k != "root"]
        sections = [(k, groups[k]) for k in order if k in groups]

    host = urllib.parse.urlparse(base).netloc.replace(".", "_")
    out = Path(a.out) if a.out else \
        Path("docs_md" if fmt == "md" else "docs_txt") / host
    out.mkdir(parents=True, exist_ok=True)

    # ---- fetch pages, expanding short "index" pages (e.g. Doxygen group
    # listings such as Functions / Data types) with their child pages -------
    # chrome/index pages excluded from index-page child expansion, by exact
    # stem (prefix matching would wrongly exclude content pages like
    # structosThreadAttr_t.html / classFoo.html)
    EXCLUDE_STEMS = {"index", "pages", "modules", "files", "annotated",
                     "globals", "dirs", "namespaces", "search",
                     "navtree", "doxygen", "menudata", "cookie", "resize",
                     "dynsections", "tabs", "classes", "functions",
                     "functions_vars"}
    EXCLUDE_PREFIXES = ("dir_",)
    INDEX_MIN_CHARS = a.index_min   # shorter page text => index page, expand

    def children_of(url):
        out = []
        for m in re.finditer(r'href="([^"#]+\.html?)"', fetch(url)):
            child = urllib.parse.urljoin(url, m.group(1))
            cu = urllib.parse.urlparse(child)
            stem = cu.path.rsplit("/", 1)[-1].rsplit(".", 1)[0]
            if cu.netloc != urllib.parse.urlparse(base).netloc:
                continue
            if stem in EXCLUDE_STEMS or stem.startswith(EXCLUDE_PREFIXES):
                continue
            out.append(child)
        return out

    def convert(url):
        html = normalize_unicode(fetch(url))
        if fmt == "md":
            return to_markdown(html, url, a.strip)
        return to_text(html, a.strip)

    section_pages = []   # [(title, [(url, text), ...]), ...]
    included = set()

    for title, pages in sections:
        entries = []
        for p in pages:
            url = urllib.parse.urljoin(base, p)
            if url in included:
                continue
            included.add(url)
            say(f"  fetching {url}")
            entries.append((url, convert(url)))
            if len(entries[-1][1]) < INDEX_MIN_CHARS:
                for child in children_of(url):
                    if child not in included:
                        included.add(child)
                        say(f"  fetching {child} (index child)")
                        entries.append((child, convert(child)))
        section_pages.append((title, entries))
    all_pages = [e for _, es in section_pages for e in es]

    def write(fname, text):
        (out / fname).write_text(text, encoding="utf-8")
        return fname

    if a.flat:
        name = write(f"ALL_DOCS{ext}", "\n".join(
            (md_page_block(t, u) if fmt == "md" else txt_header(u, u) + t)
            for u, t in all_pages))
        say(f"wrote {out}/{name}")
    elif a.per_page:
        used = set()
        for u, t in all_pages:
            stem = Path(urllib.parse.urlparse(u).path).stem or "index"
            name = sanitize(stem)
            if name in used:  # same stems on different sites/sections
                i = 2
                while f"{name}_{i}" in used:
                    i += 1
                name = f"{name}_{i}"
            used.add(name)
            if fmt == "md":
                write(f"{name}{ext}", md_page_block(t, u))
            else:
                write(f"{name}{ext}", txt_header(t.split("\n", 1)[0], u) + t)
        say(f"wrote {len(all_pages)} per-page {ext} files to {out}")
    else:
        for idx, (title, entries) in enumerate(section_pages, 1):
            if not entries:
                say(f"skipped empty section '{title}' "
                    "(its pages were already pulled into an earlier section)")
                continue
            fname = f"{idx:02d}_{sanitize(title)}{ext}"
            if fmt == "md":
                text = f"# {title}\n\n" + "\n".join(
                    md_page_block(t, u) for u, t in entries)
            else:
                text = "\n".join(txt_header(title, u) + t for u, t in entries)
            write(fname, text)
            say(f"wrote {out}/{fname} ({len(entries)} pages)")
    say(f"total: {len(all_pages)} pages -> {out} [{fmt}]")


if __name__ == "__main__":
    main()
